#!/usr/bin/env node
/**
 * Writes a right-to-left copy of every plain stylesheet in assets/css.
 *
 * wp-scripts makes `-rtl.css` files for everything it builds from src/,
 * but assets/css is served as is, so `npm run build` runs this after
 * wp-scripts. It uses the rtlcss that `@wordpress/scripts` installs (the
 * same version wp-scripts uses), so the two never disagree. Each file is
 * registered with wp_style_add_data( handle, 'rtl', 'replace' ).
 */
const fs = require( 'fs' );
const path = require( 'path' );
const rtlcss = require( 'rtlcss' );

const dir = path.join( __dirname, '..', 'assets', 'css' );
const sources = fs
	.readdirSync( dir )
	.filter(
		( file ) => file.endsWith( '.css' ) && ! file.endsWith( '-rtl.css' )
	);

for ( const file of sources ) {
	const css = fs.readFileSync( path.join( dir, file ), 'utf8' );
	const target = file.replace( /\.css$/, '-rtl.css' );
	const banner = `/* Generated by bin/build-rtl.js from ${ file } with rtlcss; do not edit. */\n`;
	fs.writeFileSync(
		path.join( dir, target ),
		banner + rtlcss.process( css )
	);
	process.stdout.write( `assets/css/${ target }\n` );
}
